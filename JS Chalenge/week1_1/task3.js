// Create a function called divideByTwo. 
// It should accept one parameter, divide it by 2, and return the result of the division.

function divideByTwo(parameter) {
    return parameter / 2;
}
console.log(divideByTwo(22))  // 11
console.log(divideByTwo(100)) // 50
console.log(divideByTwo(400)) // 200

const result = divideByTwo(10);
console.log(result);     // 5
console.log(result + 2); // 7