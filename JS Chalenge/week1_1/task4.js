// Finish the function sum. It accepts 2 parameters, 
// adds them up, and returns the sum of the two.

function sum(firstParametrs, secondParametrs) {
    return firstParametrs + secondParametrs; 
}

console.log(sum(1, 2))     // 3
console.log(sum(2, 2))     // 4
console.log(sum(55, 2))    // 57
console.log(sum(100, 200)) // 300